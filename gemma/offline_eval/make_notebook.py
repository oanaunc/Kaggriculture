#!/usr/bin/env python3
"""Build gemma-offline-eval.ipynb with a submission bundle embedded in it.

The notebook runs the official swegemma Evaluator (phase 1 = agent patch with
vLLM serving gemma-4-31b-it-qat-w4a16-ct on 4xL4, phase 2 = pytest) on a
deterministic subset of the 129 public tasks and writes /kaggle/working/results.json.

Usage:
  python3 gemma/offline_eval/make_notebook.py --bundle gemma/submission_cand1 \
      --n-tasks 20 --offset 0 --concurrency 2
  kaggle kernels push -p gemma/offline_eval
"""
