def find_dir(candidates, marker_glob):
    for c in candidates:
        if Path(c).is_dir():
            return Path(c)
    hits = sorted(glob.glob(marker_glob, recursive=True))
    if not hits:
        raise FileNotFoundError(f'nothing matches {marker_glob}; candidates {candidates}')
    return Path(hits[0]).parent


