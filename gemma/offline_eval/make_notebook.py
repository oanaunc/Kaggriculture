def cell(src: str, kind: str = 'code') -> dict:
    c = {'cell_type': kind, 'metadata': {}, 'source': src}
    if kind == 'code':
        c.update(outputs=[], execution_count=None)
    return c


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--bundle', default='gemma/submission_cand1')
    ap.add_argument('--n-tasks', type=int, default=20)
    ap.add_argument('--offset', type=int, default=0)
    ap.add_argument('--task-ids', default='', help='comma-separated instance_ids (overrides n/offset)')
    ap.add_argument('--concurrency', type=int, default=2)
    ap.add_argument('--seed', default='gemma-dev-v1')
    ap.add_argument('--bundle-dir', default='', help='use an attached dataset instead of embedding')
    ap.add_argument('--out', default=str(HERE / 'gemma-offline-eval.ipynb'))
    a = ap.parse_args()

    bundle = Path(a.bundle)
    embedded = {} if a.bundle_dir else embed_bundle(bundle)
    cfg = CONFIG_TMPL.format(
        bundle_name=bundle.name, n_tasks=a.n_tasks, offset=a.offset,
        task_ids=[s for s in a.task_ids.split(',') if s], seed=a.seed,
        concurrency=a.concurrency, bundle_dir=a.bundle_dir,
        embedded=json.dumps(embedded, indent=1),
    )
    nb = {
        'cells': [
            cell('# Gemma 4 Developer Agent - offline eval\nRuns the official `swegemma.Evaluator` on a '
                 'deterministic subset of the public tasks for one bundle and writes `results.json`.', 'markdown'),
            cell(cfg), cell(INSTALL), cell(BUNDLE), cell(VLLM), cell(EVAL), cell(RESULTS), cell(CLEANUP),
        ],
        'metadata': {
            'kernelspec': {'display_name': 'Python 3', 'language': 'python', 'name': 'python3'},
            'language_info': {'name': 'python'},
        },
        'nbformat': 4, 'nbformat_minor': 4,
    }
    Path(a.out).write_text(json.dumps(nb, indent=1))
    print(f'wrote {a.out}: bundle={bundle.name} files={len(embedded)} n={a.n_tasks} '
          f'offset={a.offset} concurrency={a.concurrency}')


if __name__ == '__main__':
    main()
