HERE = Path(__file__).resolve().parent
EXCLUDE_NAMES = {'README.md', '.DS_Store'}


def embed_bundle(bundle: Path) -> dict[str, str]:
    files: dict[str, str] = {}
    for p in sorted(bundle.rglob('*')):
        if not p.is_file() or p.name in EXCLUDE_NAMES or '__pycache__' in p.parts:
            continue
        rel = p.relative_to(bundle).as_posix()
        if p.suffix == '.safetensors':
            raise SystemExit(f'{rel}: LoRA weights are too big to embed; attach the bundle as a dataset (BUNDLE_DIR).')
        files[rel] = base64.b64encode(p.read_bytes()).decode()
    if 'agent.yaml' not in files:
        raise SystemExit(f'{bundle} has no root agent.yaml')
    return files


